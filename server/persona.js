export function buildSystemPrompt(topicId) {
  const topic = TOPICS[topicId];
  const topicLine = topic
    ? `\n\n지금 대화 주제: ${topic.label} — ${topic.hint}`
    : "";
  return `${BIO}${topicLine}`;
}

